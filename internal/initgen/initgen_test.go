package initgen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeTree writes files (relative path -> content) into a temp root and
// returns its absolute path.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, content := range files {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func readBuild(t *testing.T, root string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, "build.yml"))
	if err != nil {
		t.Fatalf("read build.yml: %v", err)
	}
	return string(data)
}

func TestRunCreatesGoAndNPMTasks(t *testing.T) {
	root := writeTree(t, map[string]string{
		"main.go":          "package main\nfunc main() {}\n",
		"pkg/app.go":       "package main\nfunc main() {}\n",
		"web/package.json": `{"scripts":{"build":"vite build"}}`,
	})
	got, err := Run(root)
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if !strings.Contains(got, "created build.yml with 3 suggested task(s)") {
		t.Errorf("summary = %q, want mention of 3 tasks", got)
	}

	build := readBuild(t, root)
	for _, want := range []string{
		"# Autogenerated by oseram init",
		"global:",
		"workingDirectory: ./",
		"go-pkg:",  // from pkg/app.go
		"npm-web:", // from web/package.json
		"dist/pkg",
		"npm:",
	} {
		if !strings.Contains(build, want) {
			t.Errorf("build.yml missing %q:\n%s", want, build)
		}
	}
	rootTask := "go-" + strings.ToLower(filepath.Base(root))
	if !strings.Contains(build, rootTask+":") {
		t.Errorf("build.yml missing root go task %q:\n%s", rootTask, build)
	}
}

func TestRunLeavesExistingBuildFile(t *testing.T) {
	root := writeTree(t, map[string]string{
		"main.go":   "package main\nfunc main() {}\n",
		"build.yml": "existing: true\n",
	})
	orig, _ := os.ReadFile(filepath.Join(root, "build.yml"))
	got, err := Run(root)
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if !strings.Contains(got, "already exists") {
		t.Errorf("summary = %q, want already-exists message", got)
	}
	after, _ := os.ReadFile(filepath.Join(root, "build.yml"))
	if string(orig) != string(after) {
		t.Errorf("build.yml was modified after already-exists\nbefore: %q\nafter:  %q", orig, after)
	}
}

func TestRunNoTasks(t *testing.T) {
	root := writeTree(t, map[string]string{
		"notes.txt": "nothing here\n",
	})
	got, err := Run(root)
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	if !strings.Contains(got, "no build.yml created") {
		t.Errorf("summary = %q, want no-tasks message", got)
	}
	if _, err := os.Stat(filepath.Join(root, "build.yml")); !os.IsNotExist(err) {
		t.Errorf("build.yml should not have been created: %v", err)
	}
}

func TestRunNonDirectory(t *testing.T) {
	root := writeTree(t, map[string]string{"file.txt": "x\n"})
	if _, err := Run(filepath.Join(root, "file.txt")); err == nil {
		t.Fatal("expected error for non-directory working directory")
	}
}

func TestRunSingleTaskSetsDefault(t *testing.T) {
	root := writeTree(t, map[string]string{
		"main.go": "package main\nfunc main() {}\n",
	})
	if _, err := Run(root); err != nil {
		t.Fatalf("Run: %v", err)
	}
	build := readBuild(t, root)
	name := "go-" + strings.ToLower(filepath.Base(root))
	if !strings.Contains(build, "default: "+name) {
		t.Errorf("single task should set global.default to %q, got:\n%s", name, build)
	}
}

